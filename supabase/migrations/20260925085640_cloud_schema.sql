/* ---------- computers with the desktop app ---------- */

-- A desktop app signed in to the account. It registers itself (register_device), and revoking it
-- (revoke_device) deletes its auth session, which private.session_ok then rejects at once.
create table public.devices (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  platform text not null check (platform in ('windows', 'macos', 'linux')),
  -- The auth session the device is signed in with, so revoking the device can end it.
  auth_session_id uuid,
  -- For display only: what the device does with requests from elsewhere. The desktop app keeps the real
  -- setting on the computer and never reads this one back.
  remote_start text not null default 'ask' check (remote_start in ('off', 'ask', 'auto')),
  created_at timestamptz not null default now(),
  last_seen_at timestamptz,
  revoked_at timestamptz,
  unique (user_id, id)
);

