-- PacedMind's cloud data. Every row belongs to one account (user_id), and the database itself enforces who
-- may read or change it, whichever client asks:
--
-- - Row level security limits every table to the signed-in account's rows.
-- - A restrictive policy on every table also requires a session that passed two-factor authentication
--   (aal2) and is still live (private.session_ok): a stolen password alone reads nothing, and a signed-out
--   or revoked session stops working at once instead of when its last token expires.
-- - References between rows include user_id, so a row can never point at another account's rows.
-- - Nothing here decides what runs on a computer. Agent commands, project folders and whether a project's
--   flow may start sessions live only in the desktop app (src/server/device.ts). Starting a session from
--   elsewhere is a request (launch_requests) that needs a two-factor code entered minutes before, and the
--   desktop app decides whether to run it.
--
-- Dates stay local wall-clock strings, as in the app (src/lib/dates.ts): "YYYY-MM-DD", "YYYY-MM-DDTHH:mm"
-- and timestamps "YYYY-MM-DDTHH:mm:ss". Checks below keep text in those shapes and within sane sizes, so
-- a compromised browser can't store values the desktop app would trip over.

/* ---------- helpers for policies (not exposed through the Data API) ---------- */

create schema private;
grant usage on schema private to authenticated;

-- The request comes from a session that passed two-factor authentication and still exists: signing out,
-- revoking a device and session time limits all end it.
create function private.session_ok() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(auth.jwt() ->> 'aal', '') = 'aal2'
     and exists (
       select 1 from auth.sessions s
       where s.id = nullif(auth.jwt() ->> 'session_id', '')::uuid
         and s.user_id = auth.uid()
         and (s.not_after is null or s.not_after > now())
     )
$$;

-- A second factor (authenticator code or passkey) was verified within the last `seconds`.
create function private.recent_mfa(seconds integer) returns boolean
language sql stable set search_path = '' as $$
  select exists (
    select 1
    from jsonb_array_elements(coalesce(auth.jwt() -> 'amr', '[]'::jsonb)) as a (claim)
    where a.claim ->> 'method' in ('totp', 'mfa/totp', 'webauthn', 'mfa/webauthn')
      and (a.claim ->> 'timestamp')::bigint >= extract(epoch from now())::bigint - seconds
  )
$$;

/* ---------- areas and projects ---------- */

create table public.areas (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  name text not null check (char_length(name) between 1 and 80),
  -- Prefix of the area's task keys, e.g. WRK in WRK-12.
  key text not null check (key ~ '^[A-Z][A-Z0-9]{1,7}$'),
  color text not null check (color ~ '^#[0-9A-Fa-f]{6}$'),
  sort integer not null default 0,
  unique (user_id, key),
  unique (user_id, id)
);

create table public.projects (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  area_id uuid not null,
  name text not null check (char_length(name) between 1 and 120),
  -- Own color; null means the area's color is used.
  color text check (color ~ '^#[0-9A-Fa-f]{6}$'),
  start_date text check (start_date ~ '^\d{4}-\d{2}-\d{2}$'),
  target_date text check (target_date ~ '^\d{4}-\d{2}-\d{2}$'),
  -- The agent new tasks default to. Its folder and flow switch are per computer (desktop app).
  agent text check (agent in ('claude', 'codex')),
  after_project_id uuid,
  sort integer not null default 0,
  unique (user_id, id),
  check (after_project_id is distinct from id),
  -- Deleting an area deletes its projects; their tasks stay, without a project (see tasks).
  foreign key (user_id, area_id) references public.areas (user_id, id) on delete cascade,
  foreign key (user_id, after_project_id) references public.projects (user_id, id) on delete set null (after_project_id)
);

