/* ---------- triggers ---------- */

-- Gives a new task the next key of its area: WRK-1, WRK-2… (INB-n without an area). A key that comes
-- with the row (an import) is kept, and later keys continue after it.
create function private.assign_task_key() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_prefix text;
  v_n integer;
begin
  if new.key is null or new.key = '' then
    v_prefix := coalesce((select a.key from public.areas a where a.id = new.area_id and a.user_id = new.user_id), 'INB');
    insert into public.key_counters as c (user_id, prefix, last) values (new.user_id, v_prefix, 1)
      on conflict (user_id, prefix) do update set last = c.last + 1
      returning c.last into v_n;
    new.key := v_prefix || '-' || v_n;
  else
    v_prefix := split_part(new.key, '-', 1);
    v_n := split_part(new.key, '-', 2)::integer;
    insert into public.key_counters as c (user_id, prefix, last) values (new.user_id, v_prefix, v_n)
      on conflict (user_id, prefix) do update set last = greatest(c.last, excluded.last);
  end if;
  return new;
end $$;

create trigger tasks_assign_key before insert on public.tasks
  for each row execute function private.assign_task_key();

-- A project's tasks always live in the project's area.
create function private.project_area_follows() returns trigger
language plpgsql set search_path = '' as $$
begin
  update public.tasks set area_id = new.area_id where user_id = new.user_id and project_id = new.id;
  return null;
end $$;

create trigger projects_area_follows after update of area_id on public.projects
  for each row when (new.area_id is distinct from old.area_id) execute function private.project_area_follows();

-- A request gets its times and status from the database, and only for a device that is still signed in.
-- A handful of pending requests at a time is plenty for one person.
create function private.launch_request_defaults() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if not exists (select 1 from public.devices d where d.id = new.device_id and d.user_id = new.user_id and d.revoked_at is null) then
    raise exception 'That computer is signed out of PacedMind.' using errcode = '42501';
  end if;
  if (select count(*) from public.launch_requests r
      where r.user_id = new.user_id and r.status = 'pending' and r.expires_at > now()) >= 10 then
    raise exception 'Too many session requests are waiting. Wait for them to start or expire.' using errcode = '54000';
  end if;
  new.requested_at := now();
  new.expires_at := now() + interval '10 minutes';
  new.status := 'pending';
  new.decided_at := null;
  new.session_id := null;
  new.note := null;
  return new;
end $$;

create trigger launch_requests_defaults before insert on public.launch_requests
  for each row execute function private.launch_request_defaults();

-- Bumps the account's version after any write, for live refresh.
create function private.bump_version() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  v_user uuid;
begin
  if tg_op = 'DELETE' then v_user := old.user_id; else v_user := new.user_id; end if;
  insert into public.user_state as s (user_id, version) values (v_user, 1)
    on conflict (user_id) do update set version = s.version + 1;
  return null;
end $$;

