-- A new account starts with the five default areas (src/server/account.ts has the same list).
create function private.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.areas (user_id, name, key, color, sort) values
    (new.id, 'Work', 'WRK', '#7D93B5', 0),
    (new.id, 'Personal', 'PER', '#7FA894', 1),
    (new.id, 'Health', 'HLT', '#B08A9B', 2),
    (new.id, 'Learning', 'LRN', '#9C93B8', 3),
    (new.id, 'Dev', 'DEV', '#7AA3AD', 4);
  insert into public.user_state (user_id, version) values (new.id, 0) on conflict do nothing;
  return new;
end $$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function private.handle_new_user();

/* ---------- functions the app calls ---------- */

-- Registers the desktop app signed in with this session, and returns the device's id. At most 20 devices
-- that are still signed in.
create function public.register_device(device_name text, device_platform text) returns uuid
language plpgsql security definer set search_path = '' as $$
declare
  v_id uuid;
begin
  if not private.session_ok() then
    raise exception 'Sign in with two-factor authentication first.' using errcode = '42501';
  end if;
  if (select count(*) from public.devices d where d.user_id = auth.uid() and d.revoked_at is null) >= 20 then
    raise exception 'Too many computers are signed in. Sign one out in Settings first.' using errcode = '54000';
  end if;
  insert into public.devices (user_id, name, platform, auth_session_id, last_seen_at)
    values (auth.uid(), device_name, device_platform, (auth.jwt() ->> 'session_id')::uuid, now())
    returning id into v_id;
  return v_id;
end $$;

-- The desktop app signed in again, with a new auth session: revoking the device must end that one.
create function public.claim_device(device uuid) returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not private.session_ok() then
    raise exception 'Sign in with two-factor authentication first.' using errcode = '42501';
  end if;
  update public.devices
    set auth_session_id = (auth.jwt() ->> 'session_id')::uuid, last_seen_at = now()
    where id = device and user_id = auth.uid() and revoked_at is null;
  if not found then
    raise exception 'This computer was signed out of PacedMind.' using errcode = 'P0002';
  end if;
end $$;

-- Signs a computer out: deletes its auth session, so every token of it stops working at once
-- (private.session_ok), and cancels the requests waiting for it.
create function public.revoke_device(device uuid) returns void
language plpgsql security definer set search_path = '' as $$
declare
  v_session uuid;
begin
  if not private.session_ok() then
    raise exception 'Sign in with two-factor authentication first.' using errcode = '42501';
  end if;
  update public.devices set revoked_at = now()
    where id = device and user_id = auth.uid() and revoked_at is null
    returning auth_session_id into v_session;
  if not found then
    raise exception 'That computer is already signed out.' using errcode = 'P0002';
  end if;
  if v_session is not null then
    delete from auth.sessions where id = v_session and user_id = auth.uid();
  end if;
  update public.launch_requests set status = 'canceled', decided_at = now(), note = 'The computer was signed out'
    where device_id = device and user_id = auth.uid() and status = 'pending';
end $$;

-- Deletes the account with all its data. Needs a two-factor code from the last five minutes.
create function public.delete_account() returns void
language plpgsql security definer set search_path = '' as $$
begin
  if not private.session_ok() or not private.recent_mfa(300) then
    raise exception 'Enter a current two-factor code first.' using errcode = '42501';
  end if;
  delete from auth.users where id = auth.uid();
end $$;

revoke execute on all functions in schema private from public, anon, authenticated;
grant execute on function private.session_ok() to authenticated;
grant execute on function private.recent_mfa(integer) to authenticated;
revoke execute on function public.register_device(text, text), public.claim_device(uuid), public.revoke_device(uuid), public.delete_account()
  from public, anon;
grant execute on function public.register_device(text, text), public.claim_device(uuid), public.revoke_device(uuid), public.delete_account()
  to authenticated;
