-- Nothing is readable without signing in. TRUNCATE, REFERENCES and TRIGGER are never needed by clients
-- (TRUNCATE would skip row level security).
revoke all on all tables in schema public from anon;
revoke all on all sequences in schema public from anon;
revoke truncate, references, trigger on all tables in schema public from authenticated;

-- Written only by triggers and functions.
revoke insert, update, delete on public.user_state from authenticated;
revoke insert, update on public.key_counters from authenticated;

-- Devices register through register_device (which records the auth session) and leave through
-- revoke_device (which ends it); in between only the name, the displayed remote-start setting and when it
-- was last seen change.
revoke insert, update, delete on public.devices from authenticated;
grant update (name, remote_start, last_seen_at) on public.devices to authenticated;

-- A request names the device, task and agent; the rest is set by the database. Afterwards only its outcome
-- changes.
revoke insert, update on public.launch_requests from authenticated;
grant insert (device_id, task_id, agent, requested_via) on public.launch_requests to authenticated;
grant update (status, decided_at, session_id, note) on public.launch_requests to authenticated;

